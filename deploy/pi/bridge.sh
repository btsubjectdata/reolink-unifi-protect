#!/bin/sh
# bridge.sh up|down|restart|logs|status|build [camera]  — runs the compose once per cameras/*.env
set -eu
cd "$(dirname "$0")"
cmd="${1:-status}"; only="${2:-}"
cams() { for f in cameras/*.env; do n=$(basename "$f" .env); case "$n" in example-*) continue;; esac; [ -z "$only" ] || [ "$n" = "$only" ] || continue; echo "$n"; done; }
dc() { n="$1"; shift; COMPOSE_PROJECT_NAME="$n" ENV_FILE="cameras/$n.env" docker compose --env-file "cameras/$n.env" "$@"; }
# mediamtx config with percent-encoded credentials (an e-mail user name or a password with
# @ # / ? breaks a URL assembled from the raw values). Holds the camera password: mode 600.
relay_cfg() {
  n="$1"; f="cameras/$n.env"; mkdir -p relay
  python3 - "$f" "relay/$n.yml" <<'PY'
import sys, urllib.parse
env = {}
for line in open(sys.argv[1]):
    line = line.strip()
    if line and not line.startswith("#") and "=" in line:
        k, v = line.split("=", 1); env[k] = v.strip().strip('"')
q = lambda s: urllib.parse.quote(s, safe="")
base = f"rtsp://{q(env['CAM_USER'])}:{q(env['CAM_PASS'])}@{env['CAM_IP']}:554/"
port = env.get("RELAY_PORT", "8554")
out = ["# generated by bridge.sh - do not edit, edit cameras/<name>.env", "logLevel: info",
       "api: no", "metrics: no", "pprof: no", "playback: no", "rtmp: no", "hls: no", "webrtc: no", "srt: no",
       "moq: no",  # mediamtx >= 1.16: on by default on :8892, collides between camera projects
       "rtsp: yes", f"rtspAddress: 127.0.0.1:{port}", "rtspTransports: [tcp]", "paths:"]
for name, key, dflt in (("hi", "HI_PATH", "stream1"), ("lo", "LO_PATH", "stream2")):
    out += [f"  {name}:", f"    source: {base}{env.get(key, dflt)}", "    rtspTransport: tcp", "    sourceOnDemand: no"]
open(sys.argv[2], "w").write("\n".join(out) + "\n")
PY
  chmod 600 "relay/$n.yml"
}
for n in $(cams); do
  case "$cmd" in
    build)   dc "$n" build ;;
    up)      mkdir -p "/dev/shm/bridge-$n"; relay_cfg "$n"; dc "$n" up -d --build ;;
    restart) relay_cfg "$n"; dc "$n" restart ;;
    down)    dc "$n" down ;;
    logs)    dc "$n" logs -f --tail 100 2>&1 | sed -E -u 's#(rtsp://)[^[:space:]"]*@#\1***:***@#g' ;;
    status)  echo "== $n"; dc "$n" ps --format 'table {{.Name}}\t{{.Status}}' ;;
    *) echo "usage: $0 up|down|restart|logs|status|build [camera]"; exit 1 ;;
  esac
done
