#!/bin/bash
# run-relay.sh — local RTSP relay (mediamtx) in the foreground. Used by launchd (InstallService.command).
#
# Pulls every camera's high and low stream from the camera ONCE and re-serves them on
# rtsp://127.0.0.1:8554/<camera>-hi and /<camera>-lo. Protect asks a "G5 Pro" for three streams
# (video1 high, video2 medium, video3 low) and the proxy spawns one ffmpeg per stream; against a
# Tapo (two RTSP sessions max) that is one too many and Protect ends up restarting streams every
# few seconds. Behind the relay the camera always sees exactly two sessions.
set -u
. "$(dirname "$0")/lib.sh"
load_env
MTX="$(command -v mediamtx || true)"
[ -n "$MTX" ] || { fail "mediamtx not installed — run Install.command"; exit 1; }
mkdir -p "$RUNTIME" "$LOGDIR"

{
  echo "# generated by run-relay.sh $(date '+%F %T') — do not edit, edit cameras/<name>.env"
  echo "logLevel: info"
  echo "logDestinations: [stdout]"
  echo "api: no"
  echo "metrics: no"
  echo "pprof: no"
  echo "playback: no"
  echo "rtsp: yes"
  echo "rtspAddress: 127.0.0.1:$RELAY_PORT"
  echo "rtspTransports: [tcp]"
  echo "rtmp: no"
  echo "hls: no"
  echo "webrtc: no"
  echo "srt: no"
  echo "paths:"
  n=0
  for cam in $(list_cameras); do
    load_camera "$cam"
    relay_on || continue
    check_camera >/dev/null 2>&1 || { warn "[$cam] incomplete config, not relayed" >&2; continue; }
    base="$(rtsp_base)"
    for s in hi lo; do
      path="$HI_PATH"; [ "$s" = lo ] && path="$LO_PATH"
      echo "  $cam-$s:"
      echo "    source: $base/$path"
      echo "    rtspTransport: tcp"
      echo "    sourceOnDemand: no"
    done
    n=$((n+1))
  done
  [ "$n" -gt 0 ] || echo "  # no cameras with RELAY=1"
} > "$RELAY_CFG"
chmod 600 "$RELAY_CFG"   # holds camera passwords
echo "[$(date '+%F %T')] relay: $(grep -c '^  [a-z0-9_-]*-\(hi\|lo\):' "$RELAY_CFG") streams on 127.0.0.1:$RELAY_PORT ($(mask_url < "$RELAY_CFG" | grep -o 'rtsp://[^ ]*' | tr '\n' ' '))"
# mediamtx echoes source URLs in a few messages; keep credentials out of the log
exec > >(sed -E -u 's#(rtsp://)[^[:space:]"]*@#\1***:***@#g') 2>&1
exec "$MTX" "$RELAY_CFG"
